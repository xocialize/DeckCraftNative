#!/usr/bin/env python3
"""Writes Sources/DCText/UnicodeTables.generated.swift from the Rust crates deckcraft's text layout uses:

- unicode-bidi 0.3.18 (MIT OR Apache-2.0): the Bidi_Class range table (Unicode 16.0);
- unicode-linebreak 0.1.5 (Apache-2.0): the line-break property trie and the UAX #14 pair table
  (Unicode 15.0).

    gen-unicode-tables.py [CARGO_REGISTRY_SRC_DIR]

The registry directory defaults to the first ~/.cargo/registry/src/*/. Swift has neither property, and
using the same tables keeps line breaks and bidi levels identical to deckcraft's.
"""
import glob
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
reg = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(os.path.expanduser("~/.cargo/registry/src/*/")))[0]
bidi = open(os.path.join(reg, "unicode-bidi-0.3.18/src/char_data/tables.rs")).read()
lb_tables = open(os.path.join(reg, "unicode-linebreak-0.1.5/src/tables.rs")).read()
lb_shared = open(os.path.join(reg, "unicode-linebreak-0.1.5/src/shared.rs")).read()

BIDI = ["AL", "AN", "B", "BN", "CS", "EN", "ES", "ET", "FSI", "L", "LRE", "LRI", "LRO", "NSM", "ON", "PDF", "PDI", "R", "RLE", "RLI", "RLO", "S", "WS"]

start = bidi.index("pub const bidi_class_table")
body = bidi[start: bidi.index("];", start)]
ranges = re.findall(r"\(\s*'\\u\{([0-9a-f]+)\}',\s*'\\u\{([0-9a-f]+)\}',\s*([A-Z]+)\s*\)", body)

# Break classes in declaration order (their u8 values) and the short aliases tables.rs uses.
enum_body = lb_shared[lb_shared.index("pub enum BreakClass {"):]
enum_body = enum_body[: enum_body.index("}")]
classes = re.findall(r"^\s*([A-Za-z]+),", enum_body, re.M)
use_block = lb_shared[lb_shared.index("use BreakClass::{"):]
use_block = use_block[: use_block.index("};")]
alias = dict((b, a) for a, b in re.findall(r"([A-Za-z]+) as ([A-Z0-9]+)", use_block))
value = {alias_name: classes.index(full) for alias_name, full in alias.items()}

def array(name):
    at = lb_tables.index("static %s:" % name)
    begin = lb_tables.index("= [", at) + 3
    return lb_tables[begin : lb_tables.index("];", begin)]

index = [int(x) for x in re.findall(r"\d+", array("BREAK_PROP_TRIE_INDEX"))]
data = [value[x] for x in re.findall(r"[A-Z0-9]+", array("BREAK_PROP_TRIE_DATA"))]
pair_rows = re.findall(r"\[([0-9,\s]+)\]", array("PAIR_TABLE"))
pairs = [[int(x) for x in row.split(",") if x.strip()] for row in pair_rows]
high_start = int(re.search(r"BREAK_PROP_TRIE_HIGH_START: u32 = (\d+)", lb_tables).group(1))

def chunks(xs, n=40):
    for i in range(0, len(xs), n):
        yield ", ".join(str(x) for x in xs[i : i + n])

out = []
out.append("// DCText — GENERATED by Packages/DCText/Scripts/gen-unicode-tables.py. Do not edit.")
out.append("// Bidi_Class ranges from unicode-bidi 0.3.18 (MIT OR Apache-2.0, Unicode 16.0); line-break property")
out.append("// trie and UAX #14 pair table from unicode-linebreak 0.1.5 (Apache-2.0, © Axel Forsman, Unicode 15.0).")
out.append("")
out.append("/// Bidi_Class values, as unicode-bidi names them.")
out.append("enum BidiClass: UInt8, Sendable {")
out.append("    case " + ", ".join(BIDI))
out.append("}")
out.append("")
out.append("/// (first, last, class), sorted and disjoint. Code points not listed are `L`.")
out.append("let bidiClassRanges: [(UInt32, UInt32, BidiClass)] = [")
for lo, hi, c in ranges:
    out.append(f"    (0x{lo.upper()}, 0x{hi.upper()}, .{c}),")
out.append("]")
out.append("")
out.append("/// Line-break classes in unicode-linebreak's `BreakClass` order: " + ", ".join(classes) + ".")
out.append("let lineBreakClassCount = %d" % len(classes))
out.append("let lineBreakTrieHighStart: UInt32 = %d" % high_start)
out.append("let lineBreakTrieIndex: [UInt16] = [")
out += ["    " + c + "," for c in chunks(index)]
out.append("]")
out.append("let lineBreakTrieData: [UInt8] = [")
out += ["    " + c + "," for c in chunks(data)]
out.append("]")
out.append("/// PAIR_TABLE[state][class]: the next state, with 0x80 = break allowed and 0x40 = break mandatory.")
out.append("let lineBreakPairTable: [[UInt8]] = [")
for row in pairs:
    out.append("    [" + ", ".join(str(x) for x in row) + "],")
out.append("]")
path = os.path.join(here, "..", "Sources", "DCText", "UnicodeTables.generated.swift")
open(path, "w").write("\n".join(out) + "\n")
print(f"{len(ranges)} bidi ranges, {len(index)} trie index, {len(data)} trie data, {len(pairs)}x{len(pairs[0])} pairs, {len(classes)} classes")
